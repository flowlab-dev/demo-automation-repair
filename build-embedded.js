/*
 * The page has to open straight from the file system, and browsers refuse to
 * fetch JSON over file://. So the three workflow files are copied verbatim
 * into one JavaScript file the page can load with a <script> tag.
 *
 * Run: node build-embedded.js
 * The test suite checks that the copy still matches the originals.
 */
const fs = require('fs');
const path = require('path');

const WORKFLOWS = ['order-intake-BROKEN.json', 'order-intake-FIXED.json', 'error-handler.json'];
const source = path.join(__dirname, 'workflows');
const target = path.join(__dirname, 'engine', 'workflows.embedded.js');

const payload = {};
for (const file of WORKFLOWS) {
  payload[file] = JSON.parse(fs.readFileSync(path.join(source, file), 'utf8'));
}

const banner = `/*
 * Generated by build-embedded.js — do not edit by hand.
 * Verbatim copy of demo/workflows/*.json so the page can run from file://.
 */
`;

const body = `(function (root) {
  'use strict';
  root.PalewoodWorkflows = ${JSON.stringify(payload, null, 2)};
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = root.PalewoodWorkflows;
  }
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;

fs.writeFileSync(target, banner + body);
console.log('written: engine/workflows.embedded.js (' + WORKFLOWS.length + ' workflows)');
